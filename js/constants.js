  MT.drawText = function (ctx, text, x, y, color, scale, shadowColor) {
    const str = String(text).toUpperCase();
    const s = scale || 1;
    const step = 6 * s;
    let cx = Math.floor(x);
    const cy = Math.floor(y);

    if (shadowColor) {
      ctx.fillStyle = shadowColor;
      let sx = cx;
      for (let i = 0; i < str.length; i++) {
        const g = FONT_5X7[str[i]] || FONT_5X7[' '];
        for (let r = 0; r < 7; r++) {
          const row = g[r];
          if (!row) continue;
          for (let c = 0; c < 5; c++) {
            if (row & (16 >> c)) {
              ctx.fillRect(sx + c * s + s, cy + r * s + s, s, s);
            }
          }
        }
        sx += step;
      }
    }

    ctx.fillStyle = color || MT.PALETTE.WHITE;
    for (let i = 0; i < str.length; i++) {
      const g = FONT_5X7[str[i]] || FONT_5X7[' '];
      for (let r = 0; r < 7; r++) {
        const row = g[r];
        if (!row) continue;
        for (let c = 0; c < 5; c++) {
          if (row & (16 >> c)) {
            ctx.fillRect(cx + c * s, cy + r * s, s, s);
          }
        }
      }
      cx += step;
    }
  };

  MT.measureText = function (text, scale) {
    const s = scale || 1;
    if (!text) return 0;
    return String(text).length * 6 * s - s;
  };

  MT.drawTextCentered = function (ctx, text, centerX, y, color, scale, shadowColor) {
    const w = MT.measureText(text, scale);
    MT.drawText(ctx, text, Math.floor(centerX - w / 2), y, color, scale, shadowColor);
  };
